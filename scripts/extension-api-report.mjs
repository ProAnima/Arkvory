// The declarations the extension API exports (ADR 0079, section 2; ADR 0083, section 2.6): the
// built `index.d.ts` of packages/extension-api, then every declaration reachable from its exports,
// file by file in source order, formatted as the repository formats code. Internal declarations
// that no export refers to are left out, so changing them does not change the report.
// `tests/extension-api-report.test.mjs` compares the stored report with the build, so every
// change to the contract is reviewed with its semver level. Write it after `npm run build`:
//   node scripts/extension-api-report.mjs --write
import { readFile, writeFile } from 'node:fs/promises';
import { basename, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import ts from 'typescript';

const root = fileURLToPath(new URL('../', import.meta.url));
const workspace = join(root, 'packages/extension-api');
export const reportPath = join(workspace, 'api-report.d.ts');

/** The top-level statement a declaration belongs to. */
function statementOf(node) {
  let current = node;
  while (current.parent && !ts.isSourceFile(current.parent)) current = current.parent;
  return current;
}

/** Declarations of the package that `node` refers to, aliases (imports, re-exports) resolved. */
function referenced(node, checker, inPackage) {
  const found = [];
  const visit = (child) => {
    if (ts.isIdentifier(child)) {
      let symbol = checker.getSymbolAtLocation(child);
      if (symbol && symbol.flags & ts.SymbolFlags.Alias) symbol = checker.getAliasedSymbol(symbol);
      for (const declaration of symbol?.declarations ?? [])
        if (inPackage(declaration.getSourceFile())) found.push(statementOf(declaration));
    }
    ts.forEachChild(child, visit);
  };
  visit(node);
  return found;
}

/** Statements reachable from the exports of `index.d.ts`, by file. */
function reachable(program, index, inPackage) {
  const checker = program.getTypeChecker();
  const kept = new Set();
  const queue = [];
  const keep = (statement) => {
    if (kept.has(statement) || ts.isImportDeclaration(statement)) return;
    kept.add(statement);
    queue.push(statement);
  };
  for (const exported of checker.getExportsOfModule(checker.getSymbolAtLocation(index))) {
    const symbol =
      exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    for (const declaration of symbol.declarations ?? []) keep(statementOf(declaration));
  }
  for (let next = queue.pop(); next; next = queue.pop())
    for (const statement of referenced(next, checker, inPackage)) keep(statement);
  return kept;
}

/**
 * The report text for the built declarations in `dist` (the package's own by default) and the
 * manifest version.
 */
export async function extensionApiReport(dist = join(workspace, 'dist')) {
  const manifest = JSON.parse(await readFile(join(workspace, 'package.json'), 'utf8'));
  const indexPath = join(dist, 'index.d.ts');
  const program = ts.createProgram([indexPath], {
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    noEmit: true,
    types: [],
  });
  const folder = resolve(dist);
  const inPackage = (file) => resolve(file.fileName).startsWith(folder + sep);
  const index = program.getSourceFile(indexPath);
  if (!index) throw new Error(`No declarations at ${indexPath}; run npm run build`);
  const kept = reachable(program, index, inPackage);
  const parts = [
    `// API report of ${manifest.name} ${manifest.version}.`,
    '// Generated by `node scripts/extension-api-report.mjs --write` after `npm run build`.',
    '// Only index.d.ts and the declarations its exports reach; internal ones are left out.',
    '// A removed or changed declaration needs a new major version and an ADR; an added one a minor.',
    '',
    '// index.d.ts',
    index.text.trimEnd(),
  ];
  const files = program
    .getSourceFiles()
    .filter((file) => inPackage(file) && file !== index)
    .sort((a, b) => (basename(a.fileName) < basename(b.fileName) ? -1 : 1));
  for (const file of files) {
    const statements = file.statements.filter((statement) => kept.has(statement));
    if (statements.length === 0) continue;
    parts.push('', `// ${basename(file.fileName)}`);
    for (const statement of statements) parts.push(statement.getFullText(file).trim());
  }
  const config = await prettier.resolveConfig(reportPath);
  return prettier.format(parts.join('\n') + '\n', { ...config, parser: 'typescript' });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv[2] !== '--write') throw new Error('Usage: extension-api-report.mjs --write');
  await writeFile(reportPath, await extensionApiReport());
}
